#!/usr/bin/env python3
"""Generate trace migration selectors that enumerate subcollections explicitly.

Firestore wildcard selectors (`v3_user_feeds/*/daily`) stream the parent
collection, which is empty when parent docs were never materialised. Explicit
selectors (`v3_user_feeds/{uid}/daily`) read the subcollection directly and
work regardless. Parent IDs are derived from user_profiles plus the `_global`
feed sentinel.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from backend.scripts.migrate_firestore_to_local import _firestore_client  # noqa: E402

# (subcollection-path template, uid-source)
UID_SUBCOLLECTIONS = [
    ("v3_user_feeds/{uid}/daily", "profiles+_global"),
    ("user_feeds/{uid}/daily", "profiles"),
    ("user_interactions/{uid}/daily", "profiles"),
    ("user_bookmarks/{uid}/items", "profiles"),
    ("user_weekly_wraps/{uid}/weeks", "profiles"),
]

ROOT_COLLECTIONS = [
    "user_profiles",
    "user_preferences",
    "user_patterns",
    "user_streaks",
    "user_seen_urls",
    "user_integrations",
    "free_reads",
    "free_newsletter_subscribers",
    "feedback",
    "extension_sessions",
    "agent_access_keys",
    "promoted_tools",
    "affiliate_codes",
    "affiliate_clicks",
    "affiliate_conversions",
    "app_config",
    "v3_trending_pool",
    "v3_deep_dive_pool",
    "v3_for_you_pool",
    "v3_summary_cache",
    "v3_synthesis_cache",
    "v3_extraction_cache",
    "v3_seen_urls",
    "v3_pipeline_runs",
    "v3_push_notifications",
    "v3_curated_queue",
    "newsletter_editions",
    "email_sends",
    "email_events",
    "unified_newsletters",
    "trending_news",
    "trending_news/*/topics",
    "topics",
]


def collect_uids(client) -> list[str]:
    uids: set[str] = set()
    for snapshot in client.collection("user_profiles").select([]).stream():
        uids.add(snapshot.id)
    return sorted(uids)


def build_selectors(client) -> list[str]:
    uids = collect_uids(client)
    print(f"user_profiles uids: {len(uids)}", file=sys.stderr)

    selectors = list(ROOT_COLLECTIONS)
    # The _global feed sentinel is not a user profile, so it needs an
    # explicit selector (it has no parent doc and no uid to derive from).
    selectors.append("v3_user_feeds/_global/daily")
    templates = [template for template, _ in UID_SUBCOLLECTIONS]
    for uid in uids:
        for template in templates:
            selectors.append(template.format(uid=uid))
    return selectors


def main() -> int:
    parser = argparse.ArgumentParser(description="generate trace migration selectors")
    parser.add_argument("--output", default="backend/config/trace_migration_selectors.generated.txt")
    parser.add_argument("--project-id", default=os.getenv("FIREBASE_PROJECT_ID"))
    args = parser.parse_args()

    client = _firestore_client(args.project_id)
    selectors = build_selectors(client)
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        "# Generated by build_trace_selectors.py — do not edit by hand.\n"
        + "\n".join(selectors)
        + "\n",
        encoding="utf-8",
    )
    print(f"wrote {len(selectors)} selectors -> {output}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
